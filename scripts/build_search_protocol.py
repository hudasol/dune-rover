#!/usr/bin/env python3
"""Generate docs/SEARCH_PROTOCOL.md from the phase 3 search logs, row files, references and verifier outputs.

    python3 scripts/build_search_protocol.py

The protocol (databases, inclusion and exclusion rules, verification) was fixed in research/phase3/AGENT_BRIEF.md and
research/phase3/VERIFIER_BRIEF.md before the searches; this script only counts what happened.  Deterministic; no network.
"""
import csv, glob, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P3 = os.path.join(ROOT, "research", "phase3")
TOPICS = {"planetary": ("PLN", "rover traverses and entrapment on sand and dunes (Mars, Moon, Earth analogs)"),
          "terramechanics3": ("TM3", "wheel and sand interaction in lab rigs, tilt beds and constructed slopes"),
          "mobilitymodels": ("MOB", "empirical vehicle mobility models (NRMM, cone index, WES numerics) and desert sand trials"),
          "sanddunes": ("SND, DUN", "Arabian dune sand properties, dune morphology, wind and DEM error"),
          "mappingenv": ("MAP, ENV", "traversability mapping and planning outcomes; heat, dust and sun effects")}


def num(v):
    m = re.match(r"\s*(\d+)", v or "")
    return int(m.group(1)) if m else 0


def search_counts(path):
    n = scr = ret = 0
    in_tab = False
    for line in open(path, encoding="utf-8"):
        if line.startswith("## "):
            in_tab = line.strip().lower() == "## searches"
            continue
        if in_tab and line.startswith("|") and not line.startswith("|---") and not line.lower().startswith("| #"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) >= 8:
                n += 1; scr += num(cells[5]); ret += num(cells[6])
    return n, scr, ret


def not_retrieved(path):
    txt = open(path, encoding="utf-8").read()
    i = txt.lower().find("## not retrieved")
    if i < 0:
        return 0
    sec = txt[i:].split("\n## ")[0]
    return sum(1 for l in sec.splitlines() if (l.startswith("|") and not l.startswith("|---") and not l.lower().startswith("| citation")) or l.startswith("- "))


def main():
    merged = set(l.strip() for l in open(os.path.join(P3, "MERGED.txt"), encoding="utf-8") if l.strip() and not l.startswith("#"))
    dropped = {r["id"] for r in csv.DictReader(open(os.path.join(P3, "dropped.csv"), encoding="utf-8"))}
    verdict = {}
    for f in glob.glob(os.path.join(ROOT, "research", "verify_out_batch*.csv")):
        if int(re.search(r"batch(\d+)", f).group(1)) >= 15:
            for r in csv.DictReader(open(f, encoding="utf-8")):
                verdict[r["id"]] = r["overall"]
    rows_out, tot = [], [0] * 11
    for t, (pref, scope) in TOPICS.items():
        n, scr, ret = search_counts(os.path.join(P3, f"{t}_search_log.md"))
        refs = list(csv.DictReader(open(os.path.join(P3, f"{t}_references.csv"), encoding="utf-8")))
        used = sum(1 for r in refs if r.get("rows", "").strip() and not r["rows"].strip().lower().startswith(("none", "no row", "excluded")))
        ids = [r["id"] for r in csv.DictReader(open(os.path.join(P3, f"{t}_rows.csv"), encoding="utf-8"))]
        v = [verdict.get(i, "") for i in ids]
        c = [sum(x == k for x in v) for k in ("correct", "minor_error", "material_error", "unverifiable")]
        m = len([i for i in ids if i not in dropped]) if f"{t}_rows.csv" in merged else 0
        nr = not_retrieved(os.path.join(P3, f"{t}_search_log.md"))
        vals = [n, scr, ret, used, nr, len(ids), sum(1 for x in v if x), *c, m]
        tot = [a + b for a, b in zip(tot, vals)]
        rows_out.append([t, pref, scope] + vals)
    hdr = ["Topic", "Ids", "Scope", "Searches", "Records screened", "Full texts read", "Sources used", "Not retrieved", "Rows extracted",
           "Rows verified", "Correct", "Minor", "Material", "Unverifiable", "Rows merged"]
    L = ["# Search protocol and flow (phase 3, 2026-10-20)", "",
         "Generated by `scripts/build_search_protocol.py` from the search logs, row files, reference files and verifier outputs in `research/phase3/` and `research/verify_out_batch15` onwards. Do not edit by hand.", "",
         "## Protocol (fixed before the searches)", "",
         "- **Question.** What published, quantitative evidence bears on wheeled mobility on loose dry sand and dune terrain, on the terrain and sand properties that drive it, and on mapping and planning for it, with an Arabian focus where it exists.",
         "- **Sources searched.** Crossref, OpenAlex, NASA NTRS, Zenodo, arXiv, DTIC (read through a web reader when downloads were refused), publisher open access pages, institutional and thesis repositories, and general web search for full texts. Exact query strings, dates and counts are in each topic's `research/phase3/<topic>_search_log.md`. OpenAlex and arXiv rate limited several agents for most of the session, which narrowed those two routes.",
         "- **Inclusion.** Quantitative results on slip, sinkage, drawbar pull, traction, gradeability, entrapment, motion resistance, terramechanics parameters, sand properties, dune slope and slip face geometry, wind regime, terrain classification accuracy, planning outcomes, and heat and dust effects; dry sand and dune terrain preferred; lunar and Martian evidence included with a gravity warning (`research/phase3/AGENT_BRIEF.md`).",
         "- **Exclusion.** No number and no clear finding; marketing and news; anything not read in full (listed as not retrieved, never used for a row).",
         "- **Extraction.** One agent per topic, five topics in parallel, each row with source, location, conditions and a comparability warning; every source checked by a live DOI or URL lookup on the day, with its licence (`research/phase3/<topic>_references.csv`).",
         "- **Verification.** Every new row checked by a fresh agent that saw the claim fields only and re opened the full text (`research/phase3/VERIFIER_BRIEF.md`). Corrections enter through `research/corrections.csv`; unverifiable rows are dropped (`research/phase3/dropped.csv`); a topic's rows enter `research/evidence.csv` only after all of them are verified (`research/phase3/MERGED.txt`).",
         "- **Human check.** A blinded random sample of 20 rows for the author to rate (`research/spot_check_inter_rater.md`), with agreement computed by `scripts/inter_rater_agreement.py`.", "",
         "## Flow by topic", "",
         "| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    for r in rows_out:
        L.append("| " + " | ".join(str(x) for x in r) + " |")
    L.append("| **total** | | | " + " | ".join(f"**{x}**" for x in tot) + " |")
    L += ["", "Counting rules: searches are logged lines; screened and full text counts are the agents' own numbers per search (some searches report counts as text, which count as zero here, so these columns are lower bounds); sources used are reference entries that support at least one row; not retrieved counts the entries of each log's not retrieved list.",
          "", "The earlier phases (rows TM, SIM, LRN, FLD, LEG; 2026-10-11 to 2026-10-18) followed the protocol described in `docs/REPORT.md` and are not counted above."]
    open(os.path.join(ROOT, "docs", "SEARCH_PROTOCOL.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L[-12:]))


if __name__ == "__main__":
    main()
