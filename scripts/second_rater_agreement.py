#!/usr/bin/env python3
"""Agreement between a second human rater, Huda and the verifier agents on the 20 row blinded spot check.

    python3 scripts/second_rater_agreement.py

The second rater fills research/second_rater_pack/second_rater_ratings.csv using research/second_rater_pack/WORKSHEET.md
(a copy of research/spot_check_inter_rater.md, the same 20 rows, verdicts hidden) without seeing Huda's ratings.
Reports raw agreement and Cohen's kappa for every pair (second rater and Huda, second rater and verifier, Huda and
verifier) on three classes and on two classes (material error or not), and Fleiss' kappa for the three raters where all
three rated a row.  Unverifiable verdicts are excluded and counted.  Writes research/second_rater_pack/AGREEMENT.md.
Nothing is computed until both humans have rated; empty sheets give a "not yet rated" report.
"""
import csv, glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACK = os.path.join(ROOT, "research", "second_rater_pack")
LABELS3 = ("correct", "minor_error", "material_error")


def cohen(a, b, labels):
    n = len(a)
    if n == 0:
        return float("nan"), float("nan")
    po = sum(x == y for x, y in zip(a, b)) / n
    pe = sum((a.count(l) / n) * (b.count(l) / n) for l in labels)
    return po, ((po - pe) / (1 - pe) if pe < 1 else float("nan"))


def fleiss(table, labels):
    """table: list of rows, each a list of the raters' labels (same number of raters per row)."""
    n, k = len(table), len(table[0]) if table else 0
    if n == 0 or k < 2:
        return float("nan")
    counts = [[r.count(l) for l in labels] for r in table]
    P = [(sum(c * c for c in row) - k) / (k * (k - 1)) for row in counts]
    pj = [sum(row[j] for row in counts) / (n * k) for j in range(len(labels))]
    Pbar, Pe = sum(P) / n, sum(p * p for p in pj)
    return (Pbar - Pe) / (1 - Pe) if Pe < 1 else float("nan")


def load():
    s = {r["id"]: r["second_rater_verdict"].strip() for r in csv.DictReader(open(os.path.join(PACK, "second_rater_ratings.csv"), encoding="utf-8"))}
    h = {r["id"]: r["huda_verdict"].strip() for r in csv.DictReader(open(os.path.join(ROOT, "research", "spot_check_inter_rater_ratings.csv"), encoding="utf-8"))}
    v = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "research", "verify_out_batch*.csv")), key=lambda p: int(re.search(r"batch(\d+)", p).group(1))):
        for r in csv.DictReader(open(f, encoding="utf-8")):
            v[r["id"]] = r["overall"].strip()
    return s, h, v


def main():
    s, h, v = load()
    ids = list(s)
    lines = ["# Second rater agreement", "", "Generated by `scripts/second_rater_agreement.py`.", ""]
    if not any(s.values()) or not any(h.values()):
        lines.append("Not yet rated: the second rater's sheet or Huda's sheet is still empty.")
    else:
        lines += ["| Pair | Rows | Raw agreement, 3 classes | Kappa, 3 classes | Raw agreement, material or not | Kappa, material or not |", "|---|---|---|---|---|---|"]
        for name, a_, b_ in (("second rater and Huda", s, h), ("second rater and verifier", s, v), ("Huda and verifier", h, v)):
            keep = [i for i in ids if a_.get(i) in LABELS3 and b_.get(i) in LABELS3]
            a3, b3 = [a_[i] for i in keep], [b_[i] for i in keep]
            po3, k3 = cohen(a3, b3, LABELS3)
            a2, b2 = [x == "material_error" for x in a3], [x == "material_error" for x in b3]
            po2, k2 = cohen(a2, b2, (True, False))
            lines.append(f"| {name} | {len(keep)} | {po3:.2f} | {k3:.2f} | {po2:.2f} | {k2:.2f} |")
        all3 = [[s[i], h[i], v[i]] for i in ids if s.get(i) in LABELS3 and h.get(i) in LABELS3 and v.get(i) in LABELS3]
        lines += ["", f"Fleiss' kappa, three raters, three classes: {fleiss(all3, LABELS3):.2f} on {len(all3)} rows.",
                  f"Rows rated unverifiable by the second rater: {sum(1 for i in ids if s.get(i) == 'unverifiable')}."]
    open(os.path.join(PACK, "AGREEMENT.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
