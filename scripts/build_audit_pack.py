#!/usr/bin/env python3
"""Face patch audit pack (review finding M4): a stratified random sample of lidar face patches per site, shown as image
chips for a human rater, with a worksheet to fill in. The truth of stages 25 to 28 is "steep ground" (8 connected groups
of at least 10 one metre posts at 28 deg or more); the audit measures how much of it is a sand slip face.

    PYTHONPATH=src python3 scripts/build_audit_pack.py

Sampling (fixed before any patch was looked at): per site, 100 patches, seed 20261028, stratified by size: 34 patches of
10 to 99 posts, 33 of 100 to 999 posts and 33 of 1000 posts or more (fewer when a stratum is smaller; the shortfall is
drawn from the other strata in turn). Inclusion weights are written so that precision can be estimated for all patches and for
the face area.
Outputs: research/face_patch_audit/worksheet.csv (committed, small) and research/face_patch_audit/README.md (committed);
the chips (PDF per site) go to data/derived/face_patch_audit/ (git ignored, regenerated by this script).
Each chip: NAIP colour image, lidar hillshade, and lidar slope with the patch outlined, 90 m across, north up.
PUBLISHED data (USGS 3DEP lidar, USDA NAIP); the sampling and the figures are mine.
"""
from __future__ import annotations
import csv, os, sys
import numpy as np
from scipy.ndimage import label as nd_label, find_objects

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src")); sys.path.insert(0, os.path.join(ROOT, "scripts"))
from dunerover import benchmark as B  # noqa: E402
from dunerover.terrain import hillshade  # noqa: E402
import benchmark_detection as BD  # noqa: E402

SEED = 20261028
STRATA = ((10, 99, 34), (100, 999, 33), (1000, 10 ** 9, 33))
OUTW = os.path.join(ROOT, "research", "face_patch_audit")
OUTC = os.path.join(ROOT, "data", "derived", "face_patch_audit")
HALF = 45
CLASSES = "slip_face | other_sand_scarp | rock | vegetation_or_pedestal | anthropogenic | artefact | unsure"


def main():
    import rasterio
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.backends.backend_pdf import PdfPages
    os.makedirs(OUTW, exist_ok=True); os.makedirs(OUTC, exist_ok=True)
    rng = np.random.default_rng(SEED)
    rows = []
    for site, (fname, win, _) in BD.SITES.items():
        z1, e0, n0, epsg = BD.load_lidar_window(fname, win)
        void = np.isnan(z1); z1f = B.fill_nearest(z1)
        steep, s1 = B.steep_posts(z1, void)
        lab, n = nd_label(steep, structure=np.ones((3, 3), int))
        sizes = np.bincount(lab.ravel())
        ids = np.nonzero(sizes >= B.MIN_POSTS)[0]; ids = ids[ids > 0]
        sz = sizes[ids]
        chosen, weights = [], {}
        pools = [ids[(sz >= lo) & (sz <= hi)] for lo, hi, _ in STRATA]
        alloc = [min(len(p), k) for p, (_, _, k) in zip(pools, STRATA)]
        spare = sum(k for _, _, k in STRATA) - sum(alloc)
        while spare > 0 and any(a < len(p) for a, p in zip(alloc, pools)):
            for i, p in enumerate(pools):          # the shortfall goes to the strata that still have patches, in turn
                if spare and alloc[i] < len(p):
                    alloc[i] += 1; spare -= 1
        for (lo, hi, _), pool, take in zip(STRATA, pools, alloc):
            pick = rng.choice(pool, take, replace=False) if take else []
            for p in pick:
                weights[int(p)] = (len(pool) / take, f"{lo} to {hi if hi < 10 ** 9 else 'more'}")
            chosen += list(map(int, pick))
        with rasterio.open(os.path.join(ROOT, "data", "raw", "extra", "naip", f"{site}.tif")) as ds:
            naip = ds.read([1, 2, 3]).astype(float)
        hs = hillshade(z1f, 1.0, 1.0)
        objs = find_objects(lab)
        pdf = PdfPages(os.path.join(OUTC, f"audit_{site}.pdf"))
        per_page = 4
        for i0 in range(0, len(chosen), per_page):
            fig, axs = plt.subplots(per_page, 3, figsize=(8.27, 11.69))
            for j in range(per_page):
                for ax in axs[j]:
                    ax.axis("off")
                if i0 + j >= len(chosen):
                    continue
                pid = chosen[i0 + j]
                sl = objs[pid - 1]
                rc = (sl[0].start + sl[0].stop) // 2; cc = (sl[1].start + sl[1].stop) // 2
                r0, r1 = max(0, rc - HALF), min(z1.shape[0], rc + HALF); c0, c1 = max(0, cc - HALF), min(z1.shape[1], cc + HALF)
                m = lab[r0:r1, c0:c1] == pid
                code = f"{site[:3].upper()}-{i0 + j + 1:03d}"
                img = np.moveaxis(naip[:, r0:r1, c0:c1], 0, -1)
                img = np.clip(img / max(np.nanpercentile(img, 99), 1), 0, 1)
                axs[j, 0].imshow(img); axs[j, 0].set_title(f"{code}  imagery", fontsize=8)
                axs[j, 1].imshow(hs[r0:r1, c0:c1], cmap="gray"); axs[j, 1].set_title("lidar hillshade", fontsize=8)
                axs[j, 2].imshow(s1[r0:r1, c0:c1], cmap="magma", vmin=0, vmax=45)
                axs[j, 2].contour(m, levels=[0.5], colors="#ff69b4", linewidths=1.0)
                axs[j, 2].set_title(f"slope 0 to 45 deg, patch {int(sizes[pid])} m2", fontsize=8)
                for ax in axs[j]:
                    ax.contour(m, levels=[0.5], colors="#ff69b4", linewidths=0.6) if ax is not axs[j, 2] else None
                E = e0 + cc + 0.5; N = n0 - rc - 0.5
                w, stratum = weights[pid]
                rows.append({"code": code, "site": site, "patch_posts": int(sizes[pid]), "stratum": stratum, "inclusion_weight": round(w, 3),
                             "easting": round(E, 1), "northing": round(N, 1), "epsg": epsg,
                             "max_slope_deg": round(float(s1[sl][lab[sl] == pid].max()), 1),
                             "class": "", "confidence_1_to_3": "", "rater": "", "note": ""})
            fig.suptitle(f"{site}: face patch audit, page {i0 // per_page + 1}. Pink outline: the patch. 90 m across, north up.", fontsize=9)
            fig.tight_layout(); pdf.savefig(fig, dpi=110); plt.close(fig)
        pdf.close()
        print(f"{site}: {len(chosen)} patches of {len(ids)}", flush=True)
    with open(os.path.join(OUTW, "worksheet.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)


if __name__ == "__main__":
    main()
