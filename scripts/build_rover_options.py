#!/usr/bin/env python3
"""Build docs/ROVER_OPTIONS.md from research/phase2/phase2_rover_options.csv (never hand edited).

Prices are exactly as shown on the retrieved vendor page (currency as shown, no conversion).  Anything not retrieved is 'unknown'.
"""
import csv, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = list(csv.DictReader(open(os.path.join(ROOT, "research/phase2/phase2_rover_options.csv"), encoding="utf-8")))
def u(x): return x.strip() if x and x.strip() else "unknown"
def cell(x, n=60):
    x = u(x).replace("|", "/").replace("\n", " ")
    return x if len(x) <= n else x[: n - 1].rstrip() + "..."
def price(r):
    p = u(r["price_as_shown"])
    return p if p == "unknown" else f"{p} {r['currency'].strip()}".strip()
plat = [r for r in rows if r["category"] == "platform"]
kit = [r for r in rows if r["category"] != "platform"]
out = ["# Rover and measurement kit options (costs only where a source was retrieved)", "",
       "**Status: sourcing notes, not a recommendation to buy and not an endorsement of any vendor.** Generated by `scripts/build_rover_options.py` from `research/phase2/phase2_rover_options.csv`; the full retrieval notes, conflicts between sources and suitability reasoning are in `research/phase2/rover_options_report.md`.", "",
       "Rules applied: a price or specification appears only if it was read on a retrieved vendor or documentation page; the currency is as shown and nothing is converted; tax and shipping are as stated on the page or unknown; **no vendor page retrieved states shipping to the UAE**, so delivery to the UAE is unknown for every row; **no sand slip or sinkage result was found for any listed platform** (a limited search, not proof that none exists).", "",
       f"## Platforms ({len(plat)} rows)", "",
       "| Platform | Vendor | Price as shown | Mass, kg | Wheel dia., mm | Payload, kg | Sand results found | Source |", "|---|---|---|---|---|---|---|---|"]
for r in plat:
    out.append(f"| {cell(r['item'], 45)} | {cell(r['vendor'], 25)} | {cell(price(r), 40)} | {cell(r['mass_kg'], 20)} | {cell(r['wheel_diameter_mm'], 20)} | {cell(r['payload_kg'], 20)} | {cell(r['sand_results_source'], 24)} | [link]({r['url']}) |")
out += ["", f"## Measurement kit items ({len(kit)} rows)", "", "| Category | Item | Vendor | Price as shown | Source |", "|---|---|---|---|---|"]
for r in kit:
    out.append(f"| {cell(r['category'], 25)} | {cell(r['item'], 55)} | {cell(r['vendor'], 25)} | {cell(price(r), 40)} | [link]({r['url']}) |")
out += ["", "## Reading these tables", "",
        "- Wheel diameter, mass and payload are as stated by vendors or derived from their pages; where vendor sources conflict (for example the AgileX Scout Mini) the conflict is listed in the retrieval notes and the value here may be one of several.",
        "- A cheap platform is not a validated one: wheel size, ground clearance and low speed control all matter for a sand slip test, and none of these platforms has a published sand result in the sources read.",
        "- Retrieval dates are in the CSV (2026-10-11, and 2026-10-12 for items fetched after the date changed). Prices change; confirm with the vendor.", ""]
open(os.path.join(ROOT, "docs/ROVER_OPTIONS.md"), "w", encoding="utf-8").write("\n".join(out))
print("wrote docs/ROVER_OPTIONS.md", len(plat), "platforms,", len(kit), "kit rows")
