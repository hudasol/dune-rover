#!/usr/bin/env python3
"""Write src/dunerover/data/evidence_card.json: the facts the planner quotes in every report (the resolution gate, what
is known about slip models), taken from the committed result files through scripts/phase3_values.py, so the product
and the documents can never disagree.

    PYTHONPATH=src python3 scripts/build_evidence_card.py [--check]

--check fails if the committed card differs from a fresh build (run by the local gate and CI).
"""
from __future__ import annotations
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "src")); sys.path.insert(0, os.path.join(ROOT, "scripts"))
import phase3_values as P3  # noqa: E402

OUT = os.path.join(ROOT, "src", "dunerover", "data", "evidence_card.json")


def build() -> dict:
    v = P3.values()
    by = {}
    for k in ("5", "10", "30"):
        by[k] = {"miss_min": v[f"lid6_miss_min_{k}"], "miss_max": v[f"lid6_miss_max_{k}"],
                 "false_safe_min": v[f"lid6_fs_min_{k}"], "false_safe_max": v[f"lid6_fs_max_{k}"],
                 "auc_min": v[f"lid6_auc_min_{k}"], "auc_max": v[f"lid6_auc_max_{k}"]}
    return {
        "label": "Facts from the result files of hudasol/dune-rover (SIMULATED BY ME against PUBLISHED data); generated by scripts/build_evidence_card.py",
        "lidar_tests": {
            "what": "Slip face detector and three class map at 5, 10 and 30 m against one metre USGS 3DEP lidar of North American dune fields "
                    "(stages 12 and 20). miss: share of cells containing a face of 28 degrees or more (at least 10 square metres) that the map "
                    "calls TRAVERSABLE; false_safe: share of TRAVERSABLE cells that contain such a face.",
            "n_fields": v["lid6_nsites"], "by_posting_m": by,
            "sources": ["results/terrain_validation/metrics.csv", "results/terrain_validation_phase4/metrics.csv"]},
        "slip_models": {
            "what": "Leave one study out validation of slip model families on digitised published slip against slope curves (stages 15, 21, 22); "
                    "bar fixed in advance: median held out error at most 0.15.",
            "n_heldout_curves": v["mv4_exp_existing_n"], "n_studies": v["mv4_nsources"],
            "three_families_heldout": f"{v['mv4_heldout_min']} to {v['mv4_heldout_max']}",
            "bekker_wong_heldout": v.get("mv4_bekker_wong_heldout", "not run"),
            "scaling_law_families_heldout": f"{v['mob_heldout_min']} to {v['mob_heldout_max']}",
            "verdict": "no family passes; a slip curve measured for the actual vehicle on the actual sand is needed",
            "sources": ["results/model_validation_phase4/"]},
        "closed_loop": {
            "what": "Replanning on an online slip estimate against a stop and retry control, 30 m naive routes, 5 slip fields, simulation with a modelled rover (stage 23, post hoc).",
            "replan_minus_retry_points": {"WhiteSands": f"{v['clm_WhiteSands_30_rr']} ({v['clm_WhiteSands_30_rr_ci']})",
                                          "Kelso": f"{v['clm_Kelso_30_rr']} ({v['clm_Kelso_30_rr_ci']})"},
            "sources": ["results/closed_loop/posthoc_multiseed/summary.csv"]},
    }


def main():
    card = build()
    text = json.dumps(card, indent=1, sort_keys=True) + "\n"
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if old != text:
            print("evidence card is stale: run scripts/build_evidence_card.py and commit it"); sys.exit(1)
        print("evidence card: up to date"); return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
