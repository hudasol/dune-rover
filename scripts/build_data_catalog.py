"""Generate docs/DATA_CATALOG.md from research/phase3/curves.csv and
research/phase3/sand_parameters.csv.

One section per curve (source, conditions, number of points, x range, method,
uncertainty, comparability), then one section per parameter set. The
digitisation settings are read from the matching specification file in
research/phase3/digitise/ or research/phase3/tabulated/.

Usage:
    python scripts/build_data_catalog.py
"""

from __future__ import annotations

import csv
import json
import os
import statistics
from collections import OrderedDict

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CURVES = os.path.join(REPO, "research", "phase3", "curves.csv")
PARAMS = os.path.join(REPO, "research", "phase3", "sand_parameters.csv")
SPEC_DIRS = [os.path.join(REPO, "research", "phase3", "digitise"),
             os.path.join(REPO, "research", "phase3", "tabulated")]
OUT = os.path.join(REPO, "docs", "DATA_CATALOG.md")
NR = "not reported"


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def g(v):
    """Short number format for the catalogue."""
    return f"{v:.3g}" if isinstance(v, float) else str(v)


def load_spec(cid):
    for d in SPEC_DIRS:
        p = os.path.join(d, cid + ".json")
        if os.path.exists(p):
            with open(p, encoding="utf-8") as fh:
                return os.path.relpath(p, REPO), json.load(fh)
    return None, {}


def unc_summary(rows, key):
    vals = [num(r[key]) for r in rows]
    nums = [v for v in vals if v is not None]
    if not nums:
        return NR
    s = f"median {g(statistics.median(nums))}, max {g(max(nums))}"
    if len(nums) < len(vals):
        s += f" ({len(vals) - len(nums)} of {len(vals)} points: {NR})"
    return s


def method_text(spec_path, spec):
    if not spec_path:
        return ""
    m = spec.get("marker")
    if not m:
        if "fit" in spec:
            return "Evaluated from the printed fit coefficients."
        return "Copied from the printed table or text."
    bits = [f"Raster: PDF page {spec['page']} at {spec['dpi']} dpi of `{spec['pdf']}`."]
    xa, ya = spec["x_axis"], spec["y_axis"]
    bits.append(f"Calibration: x pixels {xa['px']} = {xa['val']} ({xa.get('scale', 'linear')}); "
                f"y pixels {ya['px']} = {ya['val']} ({ya.get('scale', 'linear')}).")
    mode = m["mode"]
    if mode == "cloud":
        bits.append(f"Markers: colour mask {json.dumps(m['mask'])} in crop {m['crop']}, binned on the "
                    f"{m.get('bin_axis', 'x')} axis in steps of {m['bin_width']}; bin medians reported.")
    elif mode == "components":
        bits.append(f"Markers: connected components of colour mask {json.dumps(m['mask'])} in crop {m['crop']}"
                    + (f", opening {m['open_px']} px" if m.get("open_px") else "")
                    + (f", fragments merged within {m['merge_px']} px" if m.get("merge_px") else "") + ".")
    elif mode == "points":
        bits.append(f"Markers: {len(m['points'])} seed pixels read by eye, refined to the colour centroid "
                    f"within {m.get('refine', {}).get('radius_px', 'n/a')} px.")
    bits.append(f"Marker radius for the reading error: {m.get('marker_radius_px')} px.")
    for c in spec.get("text_checks", []):
        bits.append(f"Check against printed value: y = {c['y']} at x = {c['x']} ({c['where']}).")
    return " ".join(bits)


def main():
    with open(CURVES, encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    curves = OrderedDict()
    for r in rows:
        curves.setdefault(r["curve_id"], []).append(r)
    with open(PARAMS, encoding="utf-8") as fh:
        params = list(csv.DictReader(fh))

    sources = sorted({r["source_key"] for r in rows})
    out = []
    out.append("# Data catalogue: slip, sinkage and drawbar pull curves on dry sand\n")
    out.append("Generated by `scripts/build_data_catalog.py` from `research/phase3/curves.csv` and "
               "`research/phase3/sand_parameters.csv`. Do not edit by hand; edit the specification files "
               "in `research/phase3/digitise/` and `research/phase3/tabulated/`, run "
               "`scripts/digitise_figures.py`, then this script.\n")
    out.append(f"{len(curves)} curves, {len(rows)} points, {len(sources)} independent sources; "
               f"{len(params)} parameter sets.\n")
    out.append("## How to read the uncertainties\n")
    out.append("* `digitised_manual` and `digitised_auto` from discrete markers: x_unc and y_unc are the "
               "reading error, data units per pixel times the marker radius in pixels.\n"
               "* `digitised_auto` from dense scatter clouds (cloud mode): each point is the median of all "
               "marker pixels in a bin, and x_unc, y_unc combine the reading error with half the "
               "interquartile range of the published scatter in that bin. These are spreads, not standard errors.\n"
               "* `table` and `text`: as printed, or half the printed bin width for binned x; otherwise "
               "`not reported`.\n"
               "* `published_fit`: the authors' fit evaluated inside its stated range; fit residuals are not reported.\n"
               "* Error bars drawn in the source figures (usually 1 SD over repeat runs) were not transcribed.\n")

    out.append("## Summary\n")
    out.append("| curve_id | source | x | y | points | x range | test type | slope kind | method | comparable |")
    out.append("|---|---|---|---|---|---|---|---|---|---|")
    for cid, rs in curves.items():
        xs = [num(r["x"]) for r in rs if num(r["x"]) is not None]
        methods = ", ".join(sorted({r["method"] for r in rs}))
        r0 = rs[0]
        out.append(f"| {cid} | {r0['source_key']} | {r0['x_name']} ({r0['x_unit']}) | {r0['y_name']} ({r0['y_unit']}) "
                   f"| {len(rs)} | {g(min(xs))} to {g(max(xs))} | {r0['test_type']} | {r0['slope_kind']} | {methods} "
                   f"| {r0['comparable_to_dune_sand']} |")
    out.append("")

    out.append("## Curves\n")
    for cid, rs in curves.items():
        r0 = rs[0]
        xs = [num(r["x"]) for r in rs if num(r["x"]) is not None]
        ys = [num(r["y"]) for r in rs if num(r["y"]) is not None]
        spec_path, spec = load_spec(cid)
        out.append(f"### {cid}\n")
        out.append(f"* Source: {r0['source_title']}, <{r0['source_url']}>; {r0['figure_or_table']}, page {r0['page']}. "
                   f"Evidence row: {r0['evidence_row']}.")
        out.append(f"* Vehicle: {r0['vehicle']}; wheel diameter {r0['wheel_diameter_m']} m, width {r0['wheel_width_m']} m; "
                   f"load per wheel {r0['load_per_wheel_N']} N; grousers: {r0['grousers']}.")
        out.append(f"* Soil: {r0['soil']}; grain size {r0['grain_size_mm']} mm; bulk density {r0['bulk_density_kg_m3']} kg/m3; "
                   f"friction angle {r0['friction_angle_deg']} deg; preparation: {r0['preparation']}.")
        out.append(f"* Test: {r0['test_type']}, gravity {r0['gravity_g']} g, slope kind {r0['slope_kind']}.")
        out.append(f"* Data: {len(rs)} points of {r0['y_name']} ({r0['y_unit']}) against {r0['x_name']} ({r0['x_unit']}); "
                   f"x from {g(min(xs))} to {g(max(xs))}; y from {g(min(ys))} to {g(max(ys))}.")
        out.append(f"* Method: {', '.join(sorted({r['method'] for r in rs}))}. {method_text(spec_path, spec)}"
                   + (f" Specification: `{spec_path}`." if spec_path else ""))
        out.append(f"* Uncertainty: x_unc {unc_summary(rs, 'x_unc')}; y_unc {unc_summary(rs, 'y_unc')}.")
        out.append(f"* Comparable to dune sand: **{r0['comparable_to_dune_sand']}**. {r0['comparability_note']}\n")

    out.append("## Terramechanics parameter sets\n")
    out.append("| set | soil | kc | kphi | n | c (kPa) | phi (deg) | K or kx (m) | comparable |")
    out.append("|---|---|---|---|---|---|---|---|---|")
    for p in params:
        out.append(f"| {p['param_set_id']} | {p['soil']} | {p['kc']} {p['kc_unit']} | {p['kphi']} {p['kphi_unit']} | {p['n']} "
                   f"| {p['c_kPa']} | {p['phi_deg']} | {p['K_or_kx_m']} | {p['comparable_to_dune_sand']} |")
    out.append("")
    for p in params:
        out.append(f"### {p['param_set_id']}\n")
        out.append(f"* Source: {p['source_title']}, <{p['source_url']}>; {p['table_or_page']}.")
        out.append(f"* Soil and place: {p['soil']}; {p['location']}. Test conditions: {p['test_conditions']}.")
        out.append(f"* How obtained: {p['how_obtained']}.")
        out.append(f"* Other coefficients: {p['slip_sinkage_or_other_coefficients']}; ky {p['ky_m']} m; bulk density "
                   f"{p['bulk_density_kg_m3']} kg/m3; grain size {p['grain_size_mm']} mm.")
        out.append(f"* Comparable to dune sand: **{p['comparable_to_dune_sand']}**. {p['notes']}\n")

    notes_path = os.path.join(REPO, "research", "phase3", "curves_notes.md")
    if os.path.exists(notes_path):
        with open(notes_path, encoding="utf-8") as fh:
            out.append(fh.read().strip() + "\n")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print(f"wrote {os.path.relpath(OUT, REPO)}: {len(curves)} curves, {len(params)} parameter sets")


if __name__ == "__main__":
    main()
